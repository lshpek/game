/**
 * The kinds of collectible a player can hunt.
 *
 * NUMORA has exactly two physical kinds: a vehicle registration plate and a SIM
 * card carrying a synthetic number. There is no phone-number collectible - a number
 * is information printed on a card, never an object in its own right.
 *
 * One loop: every kind is rolled, owned, duplicated, sold and shared the same way.
 * The server decides which kind a roll produces; the client only ever sends a
 * *filter*.
 */
export type CollectibleKind = 'VEHICLE_PLATE' | 'SIM_CARD';

export const COLLECTIBLE_KINDS: readonly CollectibleKind[] = ['VEHICLE_PLATE', 'SIM_CARD'] as const;

/**
 * Type-specific payload stored on a SIM card.
 *
 * Every number here is synthetic: generated by the backend and printed on the card.
 * The client renders it and never composes one.
 */
export interface SimCardDetails {
  /** Stable provider code from the catalogue. */
  operator_code: string;
  operator: string;
  operator_local: string;
  /** False marks a documented game brand, so nothing implies a real carrier. */
  operator_is_real: boolean;
  operator_visual: string;
  operator_accent: string;
  /** Game balance numbers, not claims about the operator's real tariffs or market. */
  rarity_modifier: number;
  value_modifier: number;
  series: string;
  edition: string;
  /** The number the backend generated and printed on the card. */
  synthetic_number: string;
  calling_code: string;
  synthetic: boolean;
}

