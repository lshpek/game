/**
 * One synthetic frame of the roll reel.
 *
 * A frame is a *picture*, never a result. It is generated by the backend from the real
 * catalogue with a separate RNG stream, is not persisted, and is not scored, valued or
 * granted. The real collectible arrives separately as the roll's `plate`, which is the
 * only thing the reel settles onto.
 */
export interface ReelFrame {
  plate_text: string;
  display_segments: string[];
  display_segment_gaps: boolean[];
  display_segment_kinds: string[];
  /** The same recipe contract the real card carries, so a frame renders identically. */
  visual: PlateVisual;
  /** `VEHICLE_PLATE` or `SIM_CARD` - the two collectible kinds, nothing else. */
  kind: string;
  country_code: string;
  country_name_en: string;
  country_flag: string;
}

