#: Per-country display name for the currency picker, from the country catalogue.
DEFAULT_FORMAT = "eu_long"


def format_for(country_code: str) -> PlateVisual:
    """The physical format for a country, falling back to the EU standard."""
    return FORMATS[COUNTRY_FORMATS.get(country_code, DEFAULT_FORMAT)]


def theme_for(country_code: str) -> str:
    """
    A stable recipe key for a country.

    Keyed by the country rather than by the shared format, so the payload a client renders
    is always specific to the country it belongs to and a change to one country cannot
    silently restyle another.
    """
    return f"cc_{country_code.lower()}"


def visual_for(theme: str) -> PlateVisual:
    """Resolve a recipe key back to its physical format."""
    if theme in FORMATS:
        return FORMATS[theme]
    if theme.startswith("cc_"):
        return format_for(theme[3:].upper())
    return FORMATS[DEFAULT_FORMAT]


def band_text_for(visual: PlateVisual, *, alpha2: str = "", alpha3: str = "") -> str:
    """Resolve the code printed inside a country's side band.

    An EU-style band carries the country's own ISO alpha-2 code - Poland prints ``PL``,
    Germany ``D`` - so the country identifier is never a stand-in. A format with no band
    prints no band text, whatever its source says.
    """
    if visual.band_position == "none":
        return ""
    source = visual.band_text_source
    if source == "country_alpha2":
        return str(alpha2 or "").strip().upper()[:2]
    if source == "country_alpha3":
        return str(alpha3 or "").strip().upper()[:3]
    if source == "none":
        return ""
    return visual.band_text


def region_text_for(visual: PlateVisual, *, alpha2: str = "", alpha3: str = "") -> str:
    """The identifier printed in the right-hand region compartment.

    On the CIS format that compartment carries the flag, the three-letter code and the
    region code, so the alpha-3 legend belongs there. Everything else prints nothing.
    """
    if visual.region_position != "right":
        return ""
    return str(alpha3 or "").strip().upper()[:3]


def serialize_visual(
    theme: str,
    *,
    alpha2: str = "",
    alpha3: str = "",
    country_code: str = "",
) -> dict[str, object]:
    """The JSON-serialisable visual contract for the API.

    Complete: the client can render a country's plate correctly with no knowledge of that
    country, and a new country needs no frontend change. ``country_code`` lets the payload
    carry that country's own accent colour, which is the last piece of identity a shared
    physical format cannot supply on its own.
    """
    visual = visual_for(theme)
    code = country_code or (theme[3:].upper() if theme.startswith("cc_") else "")
    data: dict[str, object] = {
        "theme": visual.theme if not theme.startswith("cc_") else theme,
        "country_code": code,
        "plate_family": visual.plate_family,
        "variant": visual.variant,
        # Physical geometry, and the ratio derived from it.
        "width_mm": visual.width_mm,
        "height_mm": visual.height_mm,
        "aspect": visual.aspect,
        "radius": visual.radius,
        "border_width": visual.border_width,
        # Surface.
        "background": visual.background,
        "background_alt": visual.background_alt,
        "border": visual.border,
        "text": visual.text,
        "muted": visual.muted,
        "accent": COUNTRY_ACCENTS.get(code, visual.accent),
        "texture": visual.texture,
        # Typography.
        "font_stack": FONT_STACKS.get(visual.font_stack, visual.font_stack),
        "font_stack_key": visual.font_stack,
        "letter_spacing": visual.letter_spacing,
        "group_gap": visual.group_gap,
        "digit_scale": visual.digit_scale,
        "letter_scale": visual.letter_scale,
        "digit_weight": visual.digit_weight,
        # Country identifier.
        "band_position": visual.band_position,
        "band_color": visual.band_color,
        "band_width": visual.band_width,
        "band_text": band_text_for(visual, alpha2=alpha2, alpha3=alpha3),
        "band_text_source": visual.band_text_source,
        "band_text_color": visual.band_text_color,
        "band_stars": visual.band_stars,
        "band_flag": visual.band_flag,
        "band_emblem": visual.band_emblem,
        # Printed header.
        "header": visual.header,
        "header_align": visual.header_align,
        "header_source": visual.header_source,
        "header_color": visual.header_color or visual.muted,
        "header_offset": visual.header_offset,
        # Region placement.
        "region_position": visual.region_position,
        "region_style": visual.region_style,
        "region_badge": visual.region_badge,
        "region_width": visual.region_width,
        "region_flag": visual.region_flag,
        "region_text": region_text_for(visual, alpha2=alpha2, alpha3=alpha3),
        "show_flag": visual.show_flag,
        "show_region_flag": visual.show_region_flag,
        # Mounting hardware.
        "mount": visual.mount,
        "mount_color": visual.mount_color,
        "mount_size": visual.mount_size,
        # Finish.
        "gloss": visual.gloss,
        "sheen": visual.sheen,
        "relief": visual.relief,
        "grain": visual.grain,
        "emblem": visual.emblem,
    }
    data.update(visual.extra)
    return data


