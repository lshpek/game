#: The EU identity band and its print colour.
EU_BAND = "#003399"
EU_BAND_TEXT = "#ffd300"


@dataclass(frozen=True, slots=True)
class PlateVisual:
    """The presentation contract for one country's plate.

    Grouped as physical shape, surface, typography, country identifier, region placement,
    mounting and finish. ``width_mm``/``height_mm`` are the real standardised size and
    ``aspect`` is *derived* from them, so a recipe can never claim a size and a ratio that
    disagree.
    """

    theme: str
    #: Physical family key. Drives the renderer's structural template.
    plate_family: str = "eu_long"
    #: Which front/rear variant this recipe represents.
    variant: str = "standard"

    # --- physical shape --------------------------------------------------
    #: Real width of the plate, in millimetres. The source of truth for its proportions.
    width_mm: int = EU_520x110[0]
    #: Real height of the plate, in millimetres.
    height_mm: int = EU_520x110[1]
    radius: str = "4px"
    border_width: str = "3px"

    @property
    def aspect(self) -> float:
        """Width : height, derived from the real physical size."""
        if not self.height_mm:
            return 1.0
        return round(self.width_mm / self.height_mm, 4)

    # --- surface ----------------------------------------------------------
    background: str = "#fbfbfa"
    background_alt: str = "#edeff2"
    border: str = "#1a1a1a"
    text: str = "#111827"
    muted: str = "#4b5563"
    accent: str = "#3b4a6b"
    texture: str = "metal"

    # --- typography -------------------------------------------------------
    font_stack: str = "euro"
    letter_spacing: str = "0.045em"
    #: Space between printed groups.
    group_gap: str = "0.7em"
    #: Digits are printed larger than letters on most real plates.
    digit_scale: float = 1.0
    letter_scale: float = 0.92
    digit_weight: int = 700

    # --- country identifier -----------------------------------------------
    #: ``"left"``/``"right"`` print a side band; ``"none"`` disables it.
    band_position: str = "left"
    band_color: str | None = EU_BAND
    #: Band width as a fraction of the plate *width*.
    band_width: float = 0.19
    #: Printed inside the band: the EU country code or a national mark.
    band_text: str = ""
    #: ``"static"`` prints ``band_text``; ``"country_alpha2"`` prints the country's own
    #: ISO alpha-2 code, which is what an EU-style band does.
    band_text_source: str = "country_alpha2"
    band_text_color: str = EU_BAND_TEXT
    #: The EU star ring, drawn as vector arcs rather than emoji.
    band_stars: bool = True
    #: ``None`` = no flag in the band; a key such as ``"ru"`` or ``"ge"`` for a flag drawn
    #: as vectors. Only formats that really carry one inside the band set this.
    band_flag: str | None = None
    #: A small drawn emblem inside the band (a crest glyph), never an emoji.
    band_emblem: str = ""

    # --- printed header ---------------------------------------------------
    header: str = ""
    header_align: str = "center"
    #: ``"static"`` uses ``header``; ``"region"`` prints the region's own name (a US
    #: state's own name, for instance); ``"none"`` hides it.
    header_source: str = "none"
    header_color: str | None = None
    #: Vertical position of the printed header as a fraction of the plate height.
    header_offset: float = 0.08

    # --- region placement --------------------------------------------------
    #: ``"right"`` = separate right-hand compartment (Russia/Kazakhstan style),
    #: ``"inline"`` = part of the printed serial, ``"badge"`` = small corner badge,
    #: ``"none"`` = the country has no separate region block.
    region_position: str = "badge"
    region_style: str = "badge"
    region_badge: bool = True
    #: Width of the region compartment as a fraction of the plate *width*.
    region_width: float = 0.12
    #: Whether the compartment prints the country's flag above the region code. True on
    #: the Russian format, where the tricolour and the ``RUS`` legend sit in the right
    #: compartment with the region code beneath them.
    region_flag: bool = False
    show_flag: bool = True
    show_region_flag: bool = True

    # --- mounting ----------------------------------------------------------
    #: Physical mounting hardware, by appearance: ``"bolts"`` = studded heads (the
    #: CIS/EU screw-and-washer look), ``"holes"`` = pressed screw holes with no head
    #: (North America, Japan), ``"none"`` = an adhesive or un-drilled plate.
    mount: str = "bolts"
    mount_color: str = "#8a9099"
    #: Size of one mounting feature as a fraction of the plate *height*.
    mount_size: float = 0.11

    # --- finish -------------------------------------------------------------
    gloss: bool = True
    #: Strength of the diagonal reflection pass, 0..1.
    sheen: float = 0.48
    #: A small printed corner mark (sponsor block, crest, class mark). ``""`` = none.
    emblem: str = ""
    #: How pronounced the raised-lettering relief is, 0..1. The renderer turns this into
    #: the letterpress shadow; a matte finish gets almost none of it.
    relief: float = 0.32
    #: Fine surface grain, 0..1. Chrome and enamel are smooth; weathered paint is not.
    grain: float = 0.15

    extra: dict[str, str] = field(default_factory=dict)


