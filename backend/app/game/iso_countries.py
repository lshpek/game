ISO_BY_ALPHA2: dict[str, IsoCountry] = {country.alpha2: country for country in ISO_COUNTRIES}
ISO_BY_ALPHA3: dict[str, IsoCountry] = {country.alpha3: country for country in ISO_COUNTRIES}


def iso_country(code: str | None) -> IsoCountry | None:
    """Resolve a 2- or 3-letter identifier (either ISO form)."""
    if not code:
        return None
    text = str(code).strip().upper()
    return ISO_BY_ALPHA3.get(text) or ISO_BY_ALPHA2.get(text)


def is_known_country(code: str | None) -> bool:
    return iso_country(code) is not None


